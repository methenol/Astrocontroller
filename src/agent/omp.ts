/**
 * Runs Oh My Pi (`omp --mode rpc`) as the telescope agent and bridges its
 * NDJSON event stream to the web UI.
 *
 * Config is generated from .env on every start:
 *   $AGENT_HOME/.omp/agent/models.yml   custom OpenAI-compatible provider "astro"
 *   $AGENT_HOME/.omp/agent/config.yml   tool exposure, model role, compaction
 *   $AGENT_HOME/.omp/agent/mcp.json     the dwarf3 MCP server (this process)
 * The workspace (cwd) holds SYSTEM.md, the agent's notes and its skills.
 */
import fs from 'node:fs';
import path from 'node:path';
import { spawn, type ChildProcess } from 'node:child_process';
import { EventEmitter } from 'node:events';
import { config } from '../config.js';
import { logger, errMsg } from '../log.js';

const log = logger('agent');

export type ChatEntry =
  | { kind: 'user'; id: string; text: string; images?: number; at: number }
  | { kind: 'assistant'; id: string; text: string; thinking: string; at: number; streaming?: boolean; thinkingMs?: number }
  | { kind: 'tool'; id: string; name: string; args: unknown; intent?: string; status: 'running' | 'ok' | 'error'; result?: string; images?: string[]; at: number; ms?: number }
  | { kind: 'notice'; id: string; level: 'info' | 'warn' | 'error'; text: string; at: number };

const yamlStr = (s: string) => JSON.stringify(s);

/** What the agent is doing right now (for the status line). */
export type Activity = { kind: 'idle' | 'thinking' | 'writing' | 'tool' | 'compacting' | 'retrying'; tool?: string; since: number };
export interface TodoPhase {
  name: string;
  tasks: Array<{ content: string; status: 'pending' | 'in_progress' | 'completed' | 'abandoned' | 'blocked'; blocker?: string }>;
}

function copyDirIfMissing(src: string, dest: string): void {
  if (!fs.existsSync(src)) return;
  fs.mkdirSync(dest, { recursive: true });
  for (const e of fs.readdirSync(src, { withFileTypes: true })) {
    const s = path.join(src, e.name);
    const d = path.join(dest, e.name);
    if (e.isDirectory()) copyDirIfMissing(s, d);
    else if (!fs.existsSync(d)) fs.copyFileSync(s, d);
  }
}

export class AgentBridge extends EventEmitter {
  private proc: ChildProcess | null = null;
  private buf = '';
  private reqSeq = 0;
  private pending = new Map<string, { resolve: (v: any) => void; reject: (e: Error) => void }>();
  private chunks: { id: string; parts: string[]; count: number } | null = null;
  private stopping = false;
  private restartDelay = 2000;
  private mcpUrl = '';
  history: ChatEntry[] = [];
  busy = false;
  ready = false;
  model = '';
  thinking = config.llm.reasoningEffort;
  lastError: string | null = null;
  activity: Activity = { kind: 'idle', since: Date.now() };
  turnStartedAt: number | null = null;
  queue: { steering: string[]; followUp: string[] } = { steering: [], followUp: [] };
  todos: TodoPhase[] = [];
  context: { tokens: number; contextWindow: number; percent: number } | null = null;
  tokensPerSecond: number | null = null;
  /** first thinking delta of each streaming message, to time the reasoning */
  private thinkStart = new Map<string, number>();
  private toolEmitAt = new Map<string, number>();

  get skillsDir(): string {
    return path.join(config.paths.workspace, '.omp', 'skills');
  }

  private writeConfig(): void {
    const agentDir = path.join(config.paths.home, '.omp', 'agent');
    fs.mkdirSync(agentDir, { recursive: true });
    const { llm } = config;
    const compat: string[] = ['          stripImageInput: false'];
    if (llm.thinkingFormat) compat.push(`          thinkingFormat: ${yamlStr(llm.thinkingFormat)}`);
    fs.writeFileSync(
      path.join(agentDir, 'models.yml'),
      [
        '# Generated by Astrocontroller from .env — edits are overwritten on restart.',
        'providers:',
        '  astro:',
        `    baseUrl: ${yamlStr(llm.baseUrl)}`,
        '    api: openai-completions',
        '    apiKey: ASTRO_LLM_API_KEY',
        '    models:',
        `      - id: ${yamlStr(llm.model)}`,
        `        name: ${yamlStr(llm.model)}`,
        `        reasoning: ${llm.reasoningEffort !== 'off'}`,
        `        input: [${llm.vision ? 'text, image' : 'text'}]`,
        `        contextWindow: ${llm.contextWindow}`,
        `        maxTokens: ${llm.maxTokens}`,
        '        cost: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0 }',
        '        compat:',
        ...compat,
        '',
      ].join('\n'),
    );
    fs.writeFileSync(
      path.join(agentDir, 'config.yml'),
      [
        '# Generated by Astrocontroller.',
        'modelRoles:',
        `  default: ${yamlStr(`astro/${llm.model}`)}`,
        'tools:',
        '  xdev: false # expose the telescope MCP tools directly to the model',
        'autolearn:',
        '  enabled: false',
        'mcp:',
        '  startupTimeoutMs: 0',
        '# No idling: the agent has no wait tool, and bash cannot be used to sleep instead.',
        'bash:',
        '  patterns:',
        ...['sleep*', '*/sleep *', 'usleep*', 'timeout *', 'wait', 'wait *', 'watch *', '*setTimeout*', '*time.sleep*', '*Bun.sleep*', 'read -t*'].map(
          (m) => `    - { match: ${yamlStr(m)}, approval: deny }`,
        ),
        '',
      ].join('\n'),
    );
    fs.writeFileSync(
      path.join(agentDir, 'mcp.json'),
      JSON.stringify({ mcpServers: { dwarf3: { type: 'http', url: this.mcpUrl, timeout: 900000 } } }, null, 2),
    );
  }

  private seedWorkspace(): void {
    const ws = config.paths.workspace;
    const tmpl = config.paths.agentTemplate;
    copyDirIfMissing(path.join(tmpl, 'skills'), this.skillsDir);
    // Device reference (manual, specs): read-only and shipped with the image, so replaced every start.
    const ref = path.join(ws, 'reference');
    if (fs.existsSync(path.join(tmpl, 'reference'))) {
      fs.rmSync(ref, { recursive: true, force: true });
      fs.cpSync(path.join(tmpl, 'reference'), ref, { recursive: true });
    }
    for (const f of ['SYSTEM.md', 'NOTES.md']) {
      const src = path.join(tmpl, f);
      const dest = path.join(ws, f === 'SYSTEM.md' ? '.omp/SYSTEM.md' : f);
      fs.mkdirSync(path.dirname(dest), { recursive: true });
      // SYSTEM.md tracks the shipped version unless the user customised it.
      if (fs.existsSync(src) && (!fs.existsSync(dest) || (f === 'SYSTEM.md' && fs.existsSync(dest + '.shipped') && fs.readFileSync(dest, 'utf8') === fs.readFileSync(dest + '.shipped', 'utf8')))) {
        fs.copyFileSync(src, dest);
        if (f === 'SYSTEM.md') fs.copyFileSync(src, dest + '.shipped');
      }
    }
  }

  async start(mcpUrl: string): Promise<void> {
    this.mcpUrl = config.agent.mcpUrl || mcpUrl;
    this.stopping = false;
    this.writeConfig();
    this.seedWorkspace();
    this.spawnProc();
  }

  stop(): void {
    this.stopping = true;
    this.proc?.stdin?.end();
    setTimeout(() => this.proc?.kill('SIGTERM'), 2000).unref();
  }

  private spawnProc(): void {
    const ws = config.paths.workspace;
    const args = [
      '--mode', 'rpc',
      '--model', `astro/${config.llm.model}`,
      '--thinking', config.llm.reasoningEffort,
      '--session-dir', config.paths.sessions,
      '--continue',
      '--system-prompt', path.join(ws, '.omp', 'SYSTEM.md'),
      '--tools', 'read,write,edit,grep,glob,bash,todo',
      '--no-lsp',
      '--no-title',
    ];
    log.info(`starting ${config.agent.command} (model astro/${config.llm.model} @ ${config.llm.baseUrl}, thinking ${config.llm.reasoningEffort})`);
    const proc = spawn(config.agent.command, args, {
      cwd: ws,
      env: {
        ...process.env,
        HOME: config.paths.home,
        ASTRO_LLM_API_KEY: config.llm.apiKey || 'none',
        PI_NO_TITLE: '1',
        OMP_MCP_TIMEOUT_MS: '900000',
        NO_COLOR: '1',
      },
      stdio: ['pipe', 'pipe', 'pipe'],
    });
    this.proc = proc;
    this.ready = false;
    proc.stdout!.setEncoding('utf8');
    proc.stdout!.on('data', (d: string) => this.onData(d));
    let errTail = '';
    proc.stderr!.on('data', (d: Buffer) => {
      errTail = (errTail + d.toString()).slice(-2000);
      for (const line of d.toString().split('\n')) if (line.trim()) log.debug(`omp: ${line.trim()}`);
    });
    proc.on('error', (err) => {
      this.lastError = `cannot start "${config.agent.command}": ${errMsg(err)}`;
      log.error(this.lastError);
    });
    proc.on('exit', (code, sig) => {
      this.proc = null;
      this.ready = false;
      this.setBusy(false);
      for (const p of this.pending.values()) p.reject(new Error('agent exited'));
      this.pending.clear();
      if (this.stopping) return;
      const tail = errTail.trim().split('\n').slice(-3).join(' | ');
      this.lastError = `agent exited (${code ?? sig})${tail ? `: ${tail}` : ''}`;
      log.warn(this.lastError);
      this.note('error', `Agent process exited — restarting. ${tail}`);
      setTimeout(() => this.spawnProc(), this.restartDelay);
      this.restartDelay = Math.min(this.restartDelay * 2, 60000);
      this.emit('status', this.status());
    });
  }

  private send(obj: Record<string, unknown>): void {
    this.proc?.stdin?.write(JSON.stringify(obj) + '\n');
  }

  private command<T = any>(type: string, extra: Record<string, unknown> = {}, timeoutMs = 60000): Promise<T> {
    const id = `ac_${++this.reqSeq}`;
    return new Promise<T>((resolve, reject) => {
      const t = setTimeout(() => {
        this.pending.delete(id);
        reject(new Error(`agent command ${type} timed out`));
      }, timeoutMs);
      this.pending.set(id, {
        resolve: (v) => {
          clearTimeout(t);
          resolve(v);
        },
        reject: (e) => {
          clearTimeout(t);
          reject(e);
        },
      });
      this.send({ id, type, ...extra });
    });
  }

  private onData(chunk: string): void {
    this.buf += chunk;
    let nl: number;
    while ((nl = this.buf.indexOf('\n')) >= 0) {
      const line = this.buf.slice(0, nl).trim();
      this.buf = this.buf.slice(nl + 1);
      if (!line) continue;
      let frame: any;
      try {
        frame = JSON.parse(line);
      } catch {
        log.debug(`non-JSON from omp: ${line.slice(0, 200)}`);
        continue;
      }
      this.onFrame(frame);
    }
  }

  private onFrame(f: any): void {
    if (f.type === 'rpc_chunk') {
      if (!this.chunks || this.chunks.id !== f.chunkId) this.chunks = { id: f.chunkId, parts: [], count: f.count };
      this.chunks.parts[f.index] = f.data;
      if (this.chunks.parts.filter(Boolean).length === this.chunks.count) {
        const json = Buffer.concat(this.chunks.parts.map((p) => Buffer.from(p, 'base64'))).toString('utf8');
        this.chunks = null;
        try {
          this.onFrame(JSON.parse(json));
        } catch (err) {
          log.warn(`bad reassembled frame: ${errMsg(err)}`);
        }
      }
      return;
    }
    switch (f.type) {
      case 'ready':
        void this.onReady(f);
        return;
      case 'response': {
        const p = f.id ? this.pending.get(f.id) : undefined;
        if (p) {
          this.pending.delete(f.id);
          if (f.success) p.resolve(f.data);
          else p.reject(new Error(f.error ?? 'agent command failed'));
        } else if (!f.success) {
          this.note('error', f.error ?? 'agent error');
        }
        return;
      }
      case 'agent_start':
        this.turnStartedAt = Date.now();
        this.setBusy(true);
        return;
      case 'queue_update':
        this.queue = { steering: f.steering ?? [], followUp: f.followUp ?? [] };
        this.emit('status', this.status());
        return;
      case 'auto_retry_end':
      case 'auto_compaction_end':
        this.setActivity(this.busy ? 'thinking' : 'idle');
        void this.refreshState();
        return;
      case 'tool_execution_update': {
        const e = this.history.find((h) => h.kind === 'tool' && h.id === f.toolCallId) as Extract<ChatEntry, { kind: 'tool' }> | undefined;
        const content = f.partialResult?.content;
        if (!e || !Array.isArray(content)) return;
        e.result = content.filter((c: any) => c.type === 'text').map((c: any) => c.text).join('\n').slice(-6000);
        const last = this.toolEmitAt.get(e.id) ?? 0;
        if (Date.now() - last > 500) {
          this.toolEmitAt.set(e.id, Date.now());
          this.emit('event', { kind: 'entry', entry: e });
        }
        return;
      }
      case 'prompt_result':
        if (f.status === 'error' && f.error) this.note('error', `LLM error: ${f.error.message}${f.error.httpStatus ? ` (HTTP ${f.error.httpStatus})` : ''}`);
        return;
      case 'session_settled':
        this.setBusy(false);
        void this.refreshState();
        return;
      case 'agent_end':
        if (f.yielded !== false) this.setBusy(false);
        void this.refreshState();
        return;
      case 'message_start':
        if (f.message?.role === 'assistant') this.upsertAssistant(f.messageId, '', '', true);
        return;
      case 'message_update': {
        const ev = f.assistantMessageEvent;
        if (!ev) return;
        if (ev.type === 'text_delta' || ev.type === 'thinking_delta') {
          const e = this.findAssistant(f.messageId) ?? this.upsertAssistant(f.messageId, '', '', true);
          if (ev.type === 'text_delta') {
            e.text += ev.delta;
            this.endThinking(e);
            this.setActivity('writing');
          } else {
            e.thinking += ev.delta;
            if (!this.thinkStart.has(e.id)) this.thinkStart.set(e.id, Date.now());
            this.setActivity('thinking');
          }
          this.emit('event', { kind: 'delta', id: f.messageId, channel: ev.type === 'text_delta' ? 'text' : 'thinking', delta: ev.delta });
        }
        return;
      }
      case 'message_end': {
        const m = f.message;
        if (m?.role === 'assistant') {
          const text = (m.content ?? []).filter((c: any) => c.type === 'text').map((c: any) => c.text).join('');
          const thinking = (m.content ?? []).filter((c: any) => c.type === 'thinking').map((c: any) => c.thinking).join('\n');
          const e = this.upsertAssistant(f.messageId, text, thinking, false);
          this.endThinking(e);
          if (!e.text && !e.thinking) this.history = this.history.filter((h) => h !== e);
          if (m.stopReason === 'error' && m.errorMessage) this.note('error', `LLM error: ${m.errorMessage}`);
          this.emit('event', { kind: 'entry', entry: e });
        } else if (m?.role === 'user' && !m.synthetic) {
          const content = typeof m.content === 'string' ? m.content : (m.content ?? []).filter((c: any) => c.type === 'text').map((c: any) => c.text).join('\n');
          const images = Array.isArray(m.content) ? m.content.filter((c: any) => c.type === 'image').length : 0;
          const entry: ChatEntry = { kind: 'user', id: f.messageId ?? `u${Date.now()}`, text: content, images, at: Date.now() };
          this.push(entry);
        }
        return;
      }
      case 'tool_execution_start': {
        const entry: ChatEntry = { kind: 'tool', id: f.toolCallId, name: prettyTool(f.toolName), args: f.args, intent: f.intent, status: 'running', at: Date.now() };
        this.push(entry);
        this.setActivity('tool', prettyTool(f.toolName));
        return;
      }
      case 'tool_execution_end': {
        const e = this.history.find((h) => h.kind === 'tool' && h.id === f.toolCallId) as Extract<ChatEntry, { kind: 'tool' }> | undefined;
        const content = f.result?.content ?? [];
        const textOut = content.filter((c: any) => c.type === 'text').map((c: any) => c.text).join('\n');
        const images = [...textOut.matchAll(/captures\/(agent\/[^\s]+\.jpg)/g)].map((m) => m[1]);
        const phases = f.result?.details?.phases;
        if (Array.isArray(phases)) {
          this.todos = phases;
          this.emit('status', this.status());
        }
        this.toolEmitAt.delete(f.toolCallId);
        if (this.busy) this.setActivity('thinking');
        if (e) {
          e.status = f.isError ? 'error' : 'ok';
          e.result = textOut.slice(0, 6000);
          e.images = images;
          e.ms = Date.now() - e.at;
          this.emit('event', { kind: 'entry', entry: e });
        }
        return;
      }
      case 'auto_compaction_start':
        this.note('info', 'Compacting conversation context…');
        this.setActivity('compacting');
        return;
      case 'auto_retry_start':
        this.setActivity('retrying');
        this.note('warn', `Retrying LLM request (${f.attempt ?? ''}/${f.maxAttempts ?? ''}): ${f.errorMessage ?? ''}`);
        return;
      case 'extension_error':
        this.note('warn', `extension error: ${f.error}`);
        return;
      case 'notice':
        if (f.message) this.note(f.level === 'error' ? 'error' : 'info', String(f.message));
        return;
      default:
        return;
    }
  }

  private async onReady(f: any): Promise<void> {
    try {
      if ((f.supportedProtocolVersions ?? []).includes(2)) await this.command('negotiate_protocol', { protocolVersion: 2 });
      await this.command('set_event_filter', { events: null, messageUpdates: 'delta' }).catch(() => {});
      const state = await this.command('get_state').catch(() => null);
      this.model = state?.model ? `${state.model.provider}/${state.model.id}` : `astro/${config.llm.model}`;
      this.thinking = state?.thinkingLevel ?? this.thinking;
      this.ready = true;
      this.restartDelay = 2000;
      this.lastError = null;
      await this.loadHistory();
      await this.refreshState();
      log.info(`agent ready (${this.model}, thinking ${this.thinking})`);
      this.emit('status', this.status());
    } catch (err) {
      log.warn(`agent handshake failed: ${errMsg(err)}`);
    }
  }

  /** Rebuild the chat view from the resumed session. */
  private async loadHistory(): Promise<void> {
    const res = await this.command('get_messages', {}, 30000).catch(() => null);
    const msgs: any[] = res?.messages ?? [];
    const entries: ChatEntry[] = [];
    const tools = new Map<string, Extract<ChatEntry, { kind: 'tool' }>>();
    msgs.forEach((m, i) => {
      const at = m.timestamp ?? Date.now();
      if (m.role === 'user' && !m.synthetic) {
        const t = typeof m.content === 'string' ? m.content : (m.content ?? []).filter((c: any) => c.type === 'text').map((c: any) => c.text).join('\n');
        entries.push({ kind: 'user', id: `h${i}`, text: t, at });
      } else if (m.role === 'assistant') {
        const text = (m.content ?? []).filter((c: any) => c.type === 'text').map((c: any) => c.text).join('');
        const thinking = (m.content ?? []).filter((c: any) => c.type === 'thinking').map((c: any) => c.thinking).join('\n');
        if (text || thinking) entries.push({ kind: 'assistant', id: `h${i}`, text, thinking, at });
        for (const c of m.content ?? []) {
          if (c.type === 'toolCall') {
            const e: Extract<ChatEntry, { kind: 'tool' }> = { kind: 'tool', id: c.id, name: prettyTool(c.name), args: c.arguments, status: 'ok', at };
            tools.set(c.id, e);
            entries.push(e);
          }
        }
      } else if (m.role === 'toolResult') {
        const e = tools.get(m.toolCallId);
        if (e) {
          const t = (m.content ?? []).filter((c: any) => c.type === 'text').map((c: any) => c.text).join('\n');
          e.status = m.isError ? 'error' : 'ok';
          e.result = t.slice(0, 6000);
          e.images = [...t.matchAll(/captures\/(agent\/[^\s]+\.jpg)/g)].map((x) => x[1]);
        }
      }
    });
    this.history = entries.slice(-400);
    this.emit('event', { kind: 'reset', history: this.history });
  }

  private findAssistant(id: string) {
    return this.history.find((h) => h.kind === 'assistant' && h.id === id) as Extract<ChatEntry, { kind: 'assistant' }> | undefined;
  }

  private upsertAssistant(id: string, text: string, thinking: string, streaming: boolean) {
    let e = this.findAssistant(id);
    if (!e) {
      e = { kind: 'assistant', id, text, thinking, at: Date.now(), streaming };
      this.push(e);
    } else {
      if (!streaming || text) e.text = text || e.text;
      if (!streaming || thinking) e.thinking = thinking || e.thinking;
      e.streaming = streaming;
    }
    return e;
  }

  private push(e: ChatEntry): void {
    this.history.push(e);
    if (this.history.length > 400) this.history.shift();
    this.emit('event', { kind: 'entry', entry: e });
  }

  note(level: 'info' | 'warn' | 'error', text: string): void {
    this.push({ kind: 'notice', id: `n${Date.now()}${Math.random()}`, level, text, at: Date.now() });
  }

  private setBusy(b: boolean): void {
    if (this.busy === b) return;
    this.busy = b;
    if (!b) {
      this.activity = { kind: 'idle', since: Date.now() };
      this.turnStartedAt = null;
    } else if (this.activity.kind === 'idle') this.activity = { kind: 'thinking', since: Date.now() };
    this.emit('status', this.status());
  }

  status() {
    return {
      ready: this.ready,
      busy: this.busy,
      model: this.model || `astro/${config.llm.model}`,
      thinking: this.thinking,
      baseUrl: config.llm.baseUrl,
      error: this.lastError,
      activity: this.activity,
      turnStartedAt: this.busy ? this.turnStartedAt : null,
      queue: this.queue,
      todos: this.todos,
      context: this.context,
      tokensPerSecond: this.tokensPerSecond,
    };
  }

  private setActivity(kind: Activity['kind'], tool?: string): void {
    if (this.activity.kind === kind && this.activity.tool === tool) return;
    this.activity = { kind, tool, since: Date.now() };
    this.emit('status', this.status());
  }

  private endThinking(e: Extract<ChatEntry, { kind: 'assistant' }>): void {
    const t0 = this.thinkStart.get(e.id);
    if (t0 === undefined) return;
    this.thinkStart.delete(e.id);
    e.thinkingMs = Date.now() - t0;
  }

  /** Context usage, queue, todos and speed from omp (after every turn). */
  async refreshState(): Promise<void> {
    if (!this.ready) return;
    const st = await this.command('get_state', {}, 15000).catch(() => null);
    if (!st) return;
    if (st.contextUsage) this.context = { tokens: st.contextUsage.tokens, contextWindow: st.contextUsage.contextWindow, percent: st.contextUsage.percent };
    if (st.queuedMessages) this.queue = { steering: st.queuedMessages.steering ?? [], followUp: st.queuedMessages.followUp ?? [] };
    if (Array.isArray(st.todoPhases)) this.todos = st.todoPhases;
    if (typeof st.tokensPerSecond === 'number') this.tokensPerSecond = st.tokensPerSecond;
    if (!st.isStreaming && !this.busy && this.activity.kind !== 'idle') this.activity = { kind: 'idle', since: Date.now() };
    this.emit('status', this.status());
  }

  /**
   * Send a message. While the agent works, "steer" delivers it at the next step of the running
   * turn and "followUp" queues it until the turn ends (omp's two queues).
   */
  async prompt(text: string, images: Array<{ data: string; mimeType: string }> = [], mode: 'auto' | 'steer' | 'followUp' = 'auto'): Promise<void> {
    if (!this.ready) throw new Error(this.lastError ?? 'agent is not ready yet');
    const imgs = images.map((i) => ({ type: 'image', data: i.data, mimeType: i.mimeType }));
    const behaviour = this.busy ? (mode === 'followUp' ? 'followUp' : 'steer') : undefined;
    await this.command('prompt', { message: text, images: imgs.length ? imgs : undefined, ...(behaviour ? { streamingBehavior: behaviour } : {}) }, 120000);
  }

  async removeQueued(message: string, queue: 'steering' | 'followUp'): Promise<boolean> {
    const r = await this.command<{ removed: boolean }>('remove_queued_message', { message, queue });
    await this.refreshState();
    return !!r?.removed;
  }

  async compact(): Promise<void> {
    this.note('info', 'Compacting conversation context…');
    this.setActivity('compacting');
    try {
      await this.command('compact', {}, 600000);
    } finally {
      this.setActivity(this.busy ? 'thinking' : 'idle');
      await this.refreshState();
    }
  }

  async abort(): Promise<void> {
    await this.command('abort').catch(() => {});
  }

  async newSession(): Promise<void> {
    await this.command('new_session');
    this.history = [];
    this.todos = [];
    this.emit('event', { kind: 'reset', history: [] });
    await this.refreshState();
  }

  async setThinking(level: string): Promise<void> {
    await this.command('set_thinking_level', { level });
    this.thinking = level;
    this.emit('status', this.status());
  }
}

function prettyTool(name: string): string {
  return String(name ?? '').replace(/^mcp__dwarf3_+/, '');
}
