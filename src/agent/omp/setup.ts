/**
 * What omp needs on disk before it starts, generated from .env on every start:
 *   $AGENT_HOME/.omp/agent/models.yml   custom OpenAI-compatible provider "astro"
 *   $AGENT_HOME/.omp/agent/config.yml   tool exposure, model role, compaction
 *   $AGENT_HOME/.omp/agent/mcp.json     the dwarf3 MCP server (this process)
 * and the workspace (cwd), seeded from the shipped template: SYSTEM.md, APPEND.md, the agent's
 * notes, its skills and the device reference.
 */
import fs from 'node:fs';
import path from 'node:path';
import { config } from '../../config.js';
import { writeFileAtomic } from '../../util/fs.js';

/** MCP tool calls may run this long (a dark master, a long stack start, a full star_focus sweep). */
export const MCP_TIMEOUT_MS = 45 * 60_000;

/** Shell commands that would let the agent idle instead of ending its turn. */
const IDLE_COMMANDS = ['sleep*', '*/sleep *', 'usleep*', 'timeout *', 'wait', 'wait *', 'watch *', '*setTimeout*', '*time.sleep*', '*Bun.sleep*', 'read -t*'];

const yamlStr = (s: string) => JSON.stringify(s);

export const skillsDir = () => path.join(config.paths.workspace, '.omp', 'skills');
export const systemPromptPath = () => path.join(config.paths.workspace, '.omp', 'SYSTEM.md');
export const appendPromptPath = () => path.join(config.paths.workspace, '.omp', 'APPEND.md');

export function modelsYml(): string {
  const { llm } = config;
  const compat = ['          stripImageInput: false'];
  if (llm.thinkingFormat) compat.push(`          thinkingFormat: ${yamlStr(llm.thinkingFormat)}`);
  // 2026-10-20: with a qwen format omp sends only enable_thinking unless told the template takes an
  // effort, so REASONING_EFFORT never reached vLLM and the model thought at its own (xhigh) default.
  // This sends it both as reasoning_effort and in chat_template_kwargs.
  if (llm.thinkingFormat.startsWith('qwen') && llm.reasoningEffort !== 'off') compat.push('          qwenTemplateReasoningEffort: true');
  return [
    '# Generated by Astrocontroller from .env — edits are overwritten on restart.',
    'providers:',
    '  astro:',
    `    baseUrl: ${yamlStr(llm.baseUrl)}`,
    '    api: openai-completions',
    '    apiKey: ASTRO_LLM_API_KEY',
    '    models:',
    `      - id: ${yamlStr(llm.model)}`,
    `        name: ${yamlStr(llm.model)}`,
    `        reasoning: ${llm.reasoningEffort !== 'off'}`,
    `        input: [${llm.vision ? 'text, image' : 'text'}]`,
    `        contextWindow: ${Math.round(llm.contextWindow)}`,
    `        maxTokens: ${Math.round(llm.maxTokens)}`,
    '        cost: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0 }',
    '        compat:',
    ...compat,
    '',
  ].join('\n');
}

export function configYml(): string {
  return [
    '# Generated by Astrocontroller.',
    'modelRoles:',
    `  default: ${yamlStr(`astro/${config.llm.model}`)}`,
    'tools:',
    '  xdev: false # expose the telescope MCP tools directly to the model',
    'autolearn:',
    '  enabled: false',
    'mcp:',
    '  startupTimeoutMs: 0',
    '# A duty keeps night-long todos open until dawn: a reminder at every turn end kept the agent',
    '# from ending its turn and waiting for the duty sample (2026-10-13 01:05).',
    'todo:',
    '  reminders: false',
    '# No idling: the agent has no wait tool, and bash cannot be used to sleep instead.',
    'bash:',
    '  patterns:',
    ...IDLE_COMMANDS.map((m) => `    - { match: ${yamlStr(m)}, approval: deny }`),
    '',
  ].join('\n');
}

export function writeAgentConfig(mcpUrl: string): void {
  const agentDir = path.join(config.paths.home, '.omp', 'agent');
  fs.mkdirSync(agentDir, { recursive: true });
  writeFileAtomic(path.join(agentDir, 'models.yml'), modelsYml());
  writeFileAtomic(path.join(agentDir, 'config.yml'), configYml());
  writeFileAtomic(path.join(agentDir, 'mcp.json'), JSON.stringify({ mcpServers: { dwarf3: { type: 'http', url: mcpUrl, timeout: MCP_TIMEOUT_MS } } }, null, 2));
}

/** Copy what is missing from `src` into `dest`; files already there (the agent's own edits) are kept. */
export function copyDirIfMissing(src: string, dest: string): void {
  if (!fs.existsSync(src)) return;
  fs.mkdirSync(dest, { recursive: true });
  for (const e of fs.readdirSync(src, { withFileTypes: true })) {
    const s = path.join(src, e.name);
    const d = path.join(dest, e.name);
    if (e.isDirectory()) copyDirIfMissing(s, d);
    else if (e.isFile() && !fs.existsSync(d)) fs.copyFileSync(s, d);
  }
}

const sameText = (a: string, b: string) => fs.existsSync(a) && fs.existsSync(b) && fs.readFileSync(a, 'utf8') === fs.readFileSync(b, 'utf8');

export function seedWorkspace(): void {
  const ws = config.paths.workspace;
  const tmpl = config.paths.agentTemplate;
  copyDirIfMissing(path.join(tmpl, 'skills'), skillsDir());

  // Device reference (manual, specs): read-only and shipped with the image, so replaced every start.
  const refSrc = path.join(tmpl, 'reference');
  if (fs.existsSync(refSrc)) {
    const ref = path.join(ws, 'reference');
    fs.rmSync(ref, { recursive: true, force: true });
    fs.cpSync(refSrc, ref, { recursive: true });
  }

  // SYSTEM.md tracks the shipped version unless the user customised it (it then differs from .shipped).
  const sysSrc = path.join(tmpl, 'SYSTEM.md');
  const sys = systemPromptPath();
  fs.mkdirSync(path.dirname(sys), { recursive: true });
  if (fs.existsSync(sysSrc) && (!fs.existsSync(sys) || sameText(sys, `${sys}.shipped`))) {
    fs.copyFileSync(sysSrc, sys);
    fs.copyFileSync(sysSrc, `${sys}.shipped`);
  }

  // The agent's notes: seeded once, then its own.
  const notesSrc = path.join(tmpl, 'NOTES.md');
  const notes = path.join(ws, 'NOTES.md');
  if (fs.existsSync(notesSrc) && !fs.existsSync(notes)) fs.copyFileSync(notesSrc, notes);

  // Owner-compliance rules appended to the system prompt: mandatory, so replaced every start.
  const append = path.join(tmpl, 'APPEND.md');
  if (fs.existsSync(append)) fs.copyFileSync(append, appendPromptPath());
}
